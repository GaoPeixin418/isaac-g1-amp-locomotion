#!/usr/bin/env bash
# =============================================================================
# 27 - 串行桥接：25 录完对比视频 → 自动接 26 的 λ 扫描
#
# 为什么要桥接
# -----------------------------------------------------------------------------
# 25（录像）和 26（λ 扫描）都要用显卡。并行会导致两边都拖慢：
#   实测 4096 env 训练 + 6 env 渲染同时跑，单段录像从 ~5 分钟变 18+ 分钟。
# 所以串行；但串行又意味着"录完到扫开"之间如果没人盯，GPU 就空转。
#   10-22 17:32 训练结束到 18:43 才有人接手，白烧 1 小时。
# 桥接脚本把这两段缝起来：人不在也能一路跑到最后。
#
# 用法
# -----------------------------------------------------------------------------
#   nohup bash /data/setup/27_rec_then_sweep.sh > /data/logs/rec_then_sweep.log 2>&1 &
# =============================================================================
set -uo pipefail

log() { echo "[$(date '+%m-%d %H:%M:%S')] $*"; }

# ---- 1) 等 25 录像跑完（30s 轮询）----------------------------------------
log "===== 等待 25 录像结束 ====="
while pgrep -f "[2]5_video_compare" > /dev/null 2>&1; do
    sleep 30
done
log "===== 录像已结束，成片清单 ====="
ls -la /data/videos/amp2000_*.mp4 /data/videos/amp4000_*.mp4 2>/dev/null

# ---- 2) λ 扫描 ------------------------------------------------------------
log "===== 开始 26 的 λ 扫描 ====="
bash /data/setup/26_sweep_lambda.sh
log "===== 桥接流水线全部结束 ====="
echo "=== REC THEN SWEEP DONE ==="
