#!/usr/bin/env bash
# =============================================================================
# 24 - 串行流水线：先独占显卡录完视频，再自动接上 AMP 训练
#
# 为什么要串行而不是并行
# -----------------------------------------------------------------------------
# 实测：4096 env 训练 + 6 env 渲染同时跑在同一张 3090 上时，
#   单段 700 步录像从 ~5 分钟变成 18+ 分钟，
#   而 07_mid_eval.sh 里有 `timeout -s KILL 1200`（20 分钟硬超时），
#   结果录像在写出 mp4 之前被 SIGKILL —— **白录，一个文件都不剩**。
#   （gymnasium 的 RecordVideo 只在 close 时才落盘）
# 串行的话：录像 4 段约 25 分钟，训练不受打扰，总时间反而更短。
#
# 为什么"录完自动接训练"
# -----------------------------------------------------------------------------
# 10-22 17:32 训练结束到 18:43 才有人接手，GPU 空转 1 小时。
# 把下一步挂在同一条命令里，人不盯也不空转。
#
# 用法
# -----------------------------------------------------------------------------
#   nohup env LERP=0.5 MAX_ITER=4000 bash /data/setup/24_rec_then_train.sh \
#         > /data/logs/pipe24.log 2>&1 &
# =============================================================================
set -uo pipefail

export EVAL_TIMEOUT=${EVAL_TIMEOUT:-3600}
export VIDEO_LEN=${VIDEO_LEN:-700}
LERP=${LERP:-}
MAX_ITER=${MAX_ITER:-4000}

log() { echo "[$(date '+%m-%d %H:%M:%S')] $*"; }
if [ -z "$LERP" ]; then
    log "!! 必须显式给 LERP"; exit 1
fi

# ---- 1) 录像（独占显卡）--------------------------------------------------
log "===== [1/2] 录像（独占显卡，EVAL_TIMEOUT=$EVAL_TIMEOUT）====="
NEW_CKPT=${NEW_CKPT:-model_2200.pt} \
    bash /data/setup/22_video_clean.sh
log "===== 录像阶段结束 ====="

# ---- 2) 训练（λ 已锁死）--------------------------------------------------
log "===== [2/2] 训练 LERP=$LERP MAX_ITER=$MAX_ITER ====="
LERP=$LERP MAX_ITER=$MAX_ITER SEED=42 NUM_ENVS=4096 \
    bash /data/setup/23_train_amp_sym.sh
log "===== 流水线全部结束 ====="
echo "=== PIPE 24 DONE ==="
